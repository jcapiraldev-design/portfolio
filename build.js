#!/usr/bin/env node
/*
 * Builds the site's pages from one shared <head> template.
 *
 *   src/pages/*.html   page settings + the page's <body>   (edit these)
 *   template/head.html the shared <head> for every page    (edit this)
 *        │
 *        ▼  node build.js
 *   index.html, projects/index.html, case-studies/index.html, 404.html  (generated)
 *
 * Usage:
 *   node build.js           build all pages once
 *   node build.js --watch   rebuild automatically whenever you save a source file
 *
 * No packages needed, just Node.js.
 */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const SITE = "https://jaspercapiral-dev.vercel.app";

// Which source file becomes which page
const PAGES = {
  "index.html": "index.html",
  "projects.html": "projects/index.html",
  "case-studies.html": "case-studies/index.html",
  "404.html": "404.html",
};

const esc = (s) => String(s).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

// Reads the settings comment at the top of a page:  key: value
function readSettings(src) {
  const m = src.match(/^\s*<!--([\s\S]*?)-->/);
  const settings = {};
  if (m) {
    m[1].split("\n").forEach((line) => {
      const kv = line.match(/^\s*([a-z]+):\s*(.*?)\s*$/i);
      if (kv) settings[kv[1].toLowerCase()] = kv[2];
    });
  }
  return { settings, rest: m ? src.slice(m[0].length) : src };
}

function fill(template, values, flags) {
  // {{#name}} ... {{/name}} blocks are kept only when flags[name] is true
  let out = template.replace(/\{\{#(\w+)\}\}([\s\S]*?)\{\{\/\1\}\}/g, (_, name, inner) => (flags[name] ? inner : ""));
  return out.replace(/\{\{(\w+)\}\}/g, (_, name) => (name in values ? values[name] : ""));
}

function buildPage(srcName, outName) {
  const srcPath = path.join(ROOT, "src/pages", srcName);
  const raw = fs.readFileSync(srcPath, "utf8");
  const { settings: s, rest } = readSettings(raw);

  // Optional <head-extra>...</head-extra> block goes at the end of the <head>
  let body = rest;
  let extra = "";
  body = body.replace(/<head-extra>([\s\S]*?)<\/head-extra>\s*/, (_, inner) => { extra = inner.trim() + "\n"; return ""; });

  const scripts = (s.scripts || "")
    .split(",").map((x) => x.trim()).filter(Boolean)
    .map((file) => `<script defer src="/data/js/${file}"></script>\n`).join("");

  const isPublic = !/noindex/i.test(s.robots || "");
  const head = fill(
    fs.readFileSync(path.join(ROOT, "template/head.html"), "utf8").replace(/^<!--[\s\S]*?-->\s*/, ""),
    {
      title: esc(s.title || "Jasper Capiral"),
      description: esc(s.description || ""),
      path: s.path || "/",
      robots: esc(s.robots || ""),
      site: SITE,
      scripts,
      extra,
    },
    { canonical: isPublic, robots: !!s.robots, social: isPublic && s.social !== "no" }
  );

  const html =
    `<!DOCTYPE html>\n<!-- Generated by build.js from src/pages/${srcName} and template/head.html. Edit those files, not this one. -->\n` +
    `<html lang="en">\n<head>\n${head.trim()}\n</head>\n${body.trim()}\n</html>\n`;

  const outPath = path.join(ROOT, outName);
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, html);
  console.log(`  ✓ ${outName}`);
}

function buildAll() {
  console.log("Building pages…");
  for (const [src, out] of Object.entries(PAGES)) {
    try { buildPage(src, out); } catch (err) { console.error(`  ✗ ${src}: ${err.message}`); }
  }
}

buildAll();

if (process.argv.includes("--watch")) {
  console.log("\nWatching src/pages/ and template/head.html. Press Ctrl + C to stop.");
  let timer;
  const rebuild = () => { clearTimeout(timer); timer = setTimeout(buildAll, 100); };
  fs.watch(path.join(ROOT, "src/pages"), rebuild);
  fs.watch(path.join(ROOT, "template/head.html"), rebuild);
}
